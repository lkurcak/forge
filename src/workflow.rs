//! The release workflow: repos tagged for one get a `release.yml` that only
//! calls the shared workflow, with inputs rendered from their tags.
//!
//! The file is compared as text, so it's never edited by hand. Fixes go
//! through a pull request, since default branches can require one.

use std::fmt::Write as _;

use anyhow::{Context, Result, bail};
use base64::Engine as _;
use base64::engine::general_purpose::STANDARD as BASE64;
use serde_json::{Value, json};

use crate::gh::Gh;
use crate::manifest::Repo;
use crate::reconcile::Mode;

const PATH: &str = ".github/workflows/release.yml";
const BRANCH: &str = "forge/release-workflow";

/// The `release.yml` the repo should have, if its tags name a release workflow.
pub fn render(repo: &Repo) -> Result<Option<String>> {
    let Some(uses) = &repo.release_workflow else {
        return Ok(None);
    };
    let prefix = repo.release_tag_prefix.as_deref().unwrap_or("");

    let mut inputs = repo.release_inputs.clone();
    if !repo.release_targets.is_empty() {
        if let Some(target) = repo.release_targets.iter().find(|t| t.contains('*')) {
            bail!("release target {target} needs to be exact to build it");
        }
        inputs.insert("targets".into(), repo.release_targets.join(" ").into());
    }

    let mut out = format!(
        "# Generated by forge (github.com/lkurcak/forge) from its forge.toml.
# Change the repo's tags there rather than editing this file.
name: Release

on:
  push:
    tags: [\"{prefix}[0-9]+.[0-9]+.[0-9]+\"]

jobs:
  release:
    uses: {uses}
    permissions:
      contents: write
      id-token: write
    secrets: inherit
"
    );
    if !inputs.is_empty() {
        out.push_str("    with:\n");
    }
    for (name, value) in &inputs {
        match value {
            // One target per line keeps diffs readable.
            Value::String(s) if name == "targets" => {
                writeln!(out, "      {name}: >-")?;
                for target in s.split(' ') {
                    writeln!(out, "        {target}")?;
                }
            }
            // JSON scalars are valid YAML.
            _ => writeln!(out, "      {name}: {value}")?,
        }
    }
    Ok(Some(out))
}

/// Compares the repo's `release.yml` with [`render`], and in apply mode opens
/// (or refreshes) a pull request replacing it.
pub fn drift(gh: &Gh, mode: Mode, owner: &str, repo: &Repo) -> Result<Vec<String>> {
    let Some(expected) = render(repo)? else {
        return Ok(Vec::new());
    };
    let full = format!("{owner}/{}", repo.name);
    let base = format!("repos/{full}");
    let default_branch = gh.get(&base)?["default_branch"]
        .as_str()
        .context("repo has no default branch")?
        .to_owned();

    let line = match gh.file(&full, PATH, Some(&default_branch))? {
        Some(actual) if actual == expected => return Ok(Vec::new()),
        Some(_) => format!("{PATH}: differs from what forge.toml implies"),
        None => format!("{PATH}: missing"),
    };

    let open_pr =
        gh.get(&format!("{base}/pulls?state=open&head={owner}:{BRANCH}"))?[0]["number"].as_u64();

    if !mode.applies() {
        return Ok(vec![match open_pr {
            Some(n) => format!("{line} (fix waiting in #{n})"),
            None => line,
        }]);
    }

    let sha = gh.get(&format!("{base}/git/ref/heads/{default_branch}"))?["object"]["sha"]
        .as_str()
        .context("unexpected ref response")?
        .to_owned();
    // Start the branch over from the default branch, so the PR holds only
    // the generated file.
    let created = gh.api(
        "POST",
        &format!("{base}/git/refs"),
        Some(&json!({ "ref": format!("refs/heads/{BRANCH}"), "sha": sha })),
    );
    if let Err(err) = created {
        if !err.to_string().contains("Reference already exists") {
            return Err(err);
        }
        gh.api(
            "PATCH",
            &format!("{base}/git/refs/heads/{BRANCH}"),
            Some(&json!({ "sha": sha, "force": true })),
        )?;
    }

    let mut body = json!({
        "message": "ci: generate the release workflow from forge.toml",
        "content": BASE64.encode(&expected),
        "branch": BRANCH,
    });
    match gh.get(&format!("{base}/contents/{PATH}?ref={BRANCH}")) {
        Ok(file) => body["sha"] = file["sha"].clone(),
        Err(err) if err.to_string().contains("(HTTP 404)") => {}
        Err(err) => return Err(err),
    }
    gh.api("PUT", &format!("{base}/contents/{PATH}"), Some(&body))?;

    let n = match open_pr {
        Some(n) => n,
        None => gh.api(
            "POST",
            &format!("{base}/pulls"),
            Some(&json!({
                "title": "ci: generate the release workflow from forge.toml",
                "head": BRANCH,
                "base": default_branch,
                "body": "forge renders this file from the repo's tags in \
                         [forge.toml](https://github.com/lkurcak/forge/blob/main/forge.toml).",
            })),
        )?["number"]
            .as_u64()
            .context("unexpected pull request response")?,
    };
    Ok(vec![format!("{line} (fix in #{n})")])
}

#[cfg(test)]
mod tests {
    use std::collections::BTreeMap;

    use serde_json::Map;

    use super::*;

    fn repo(inputs: &[(&str, Value)], targets: &[&str]) -> Repo {
        Repo {
            name: "gud".into(),
            tags: Vec::new(),
            settings: Map::new(),
            actions: Map::new(),
            rulesets: Vec::new(),
            variables: BTreeMap::new(),
            secrets: BTreeMap::new(),
            forbidden_secrets: Vec::new(),
            environments: Vec::new(),
            release_tag_prefix: Some("v".into()),
            release_targets: targets.iter().map(|&t| t.into()).collect(),
            release_workflow: Some("lkurcak/forge/.github/workflows/rust-release.yml@v1".into()),
            release_inputs: inputs
                .iter()
                .map(|(k, v)| ((*k).into(), v.clone()))
                .collect(),
        }
    }

    #[test]
    fn renders_inputs_and_targets() {
        let repo = repo(
            &[("winget", true.into()), ("crates-io", true.into())],
            &["aarch64-apple-darwin", "x86_64-pc-windows-msvc"],
        );
        let expected = r#"# Generated by forge (github.com/lkurcak/forge) from its forge.toml.
# Change the repo's tags there rather than editing this file.
name: Release

on:
  push:
    tags: ["v[0-9]+.[0-9]+.[0-9]+"]

jobs:
  release:
    uses: lkurcak/forge/.github/workflows/rust-release.yml@v1
    permissions:
      contents: write
      id-token: write
    secrets: inherit
    with:
      crates-io: true
      targets: >-
        aarch64-apple-darwin
        x86_64-pc-windows-msvc
      winget: true
"#;
        assert_eq!(render(&repo).unwrap().unwrap(), expected);
    }

    #[test]
    fn rejects_wildcard_targets() {
        assert!(render(&repo(&[], &["x86_64-pc-windows-*"])).is_err());
    }
}
